"""Generate shared protocol identity/limits for the optional TypeScript client."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payload = (ROOT / "catalog/agent-operations.json").read_bytes()
    catalog = json.loads(payload)
    text = "// Generated by tools/generate_ts_contract.py; do not edit.\n"
    text += f'export const CATALOG_SHA256 = "{hashlib.sha256(payload).hexdigest()}";\n'
    text += f"export const SCHEMA_VERSION = {catalog['schema_version']} as const;\n"
    text += f"export const PROFILE = {json.dumps(catalog['profile'])} as const;\n"
    text += f"export const LIMITS = {json.dumps(catalog['limits'], indent=2)} as const;\n"
    text += (
        "export const OPERATIONS = "
        + json.dumps([x["name"] for x in catalog["operations"]])
        + " as const;\n"
    )
    target = ROOT / "typescript/src/contract.ts"
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit("TypeScript protocol constants differ from the canonical catalog")
    else:
        target.write_text(text)


if __name__ == "__main__":
    main()
